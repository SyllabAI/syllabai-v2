#!/usr/bin/env python3
"""RN-DEBRIS-11 run-012 executor — stream C: the 0500 spine rebuilds of record.

The run-009 F1/F2 verdict (STRUCTURAL-REPAIR-QUEUED) executed for
cie-igcse-english-language-20 (0500, 2024-2026) and cie-igcse-english-language-25
(0500, 2027-2029): the front-matter/assessment-table wreck spines (163/209 parse
points) are rebuilt to the official 3 blocks x 6 bullets of record
(run009_official_evidence.json, PDF-pinned per run-009 G1).

Laws of the rebuild (per course):
  C1  SURVIVORS: the 18 rows whose titles byte-equal an official bullet are
      retained code-and-bytes; 3 rows per course carry bullet+glued-junk titles
      (old_title.startswith(official_bullet)) and are retitled to the official
      byte form. No other row survives. The syllabus aims (S2.001-006) are
      non-spine prose per the verdict and are dropped (disclosed).
  C2  CONTAINERS: 3 TOPICs + 3 SUBTOPICs minted (fleet T-code convention,
      blockOrder of record), provenanceTier RULE_DERIVED (fleet template,
      run-011 precedent), orders: TOPICs global 1..3, SUBTOPICs per-topic,
      SPEC_POINTs global 1..18.
  C3  EDGES: PART_OF mirror of parents (24 edges; all wreck edges retired).
  C4  MIGRATION: notes' official anchors on dying rows retract to [] (both
      fields; smeSpecPointIds preserved — the run-005 retraction law); the
      el20 '-gen' stamps TS3-gen -> T2-gen; el25 stamps TS19-gen -> T1-gen;
      el25's S22.001-005 part anchors (mark-table captures) retract to [].
      prerequisites.json (the operator-validated T-C11 store) byte-untouched.
  C5  PLANES: KG regenerated by kg_export.export_course() (pre tier strictly
      subset of served — dropped pairs must touch dying endpoints only);
      index.json rows synced; manifest counts synced (3/3/18).
Fail-closed: round-trip byte laws asserted pre-write on every touched file.
"""
import json
import sys
import collections
from pathlib import Path

REPO = Path("/home/z/my-project/work/syllabai-v2")
HUB = REPO / "apps" / "hub"
CONTENT = HUB / "content"
KG = HUB / "public" / "kg" / "data"
ART = REPO / ".syllabai" / "lane-artifacts" / "RN-DEBRIS-11"


def fail(msg):
    print(f"FAIL: {msg}", flush=True)
    sys.exit(2)


def dump_indent(obj):
    return (json.dumps(obj, indent=1, ensure_ascii=False) + "\n").encode()


def load(p):
    return json.loads(Path(p).read_text(encoding="utf-8"))


def registry():
    data = (CONTENT / "courses.json").read_text(encoding="utf-8")
    entries = json.loads(data)
    reg = {}
    for e in (entries if isinstance(entries, list) else entries.get("courses", [])):
        if isinstance(e, dict) and e.get("slug"):
            reg[e["slug"]] = e
    return reg


COURSES = {
    "cie-igcse-english-language-20": {
        "vintage": "2024-2026", "fam": "F1_0500_2024",
        "blocks": {
            "Reading": ["S2.007", "S2.008", "S2.009", "S2.010", "S2.011", "S2.012"],
            "Writing": ["S3.001", "S3.002", "S3.003", "S3.004", "S3.005", "S3.006"],
            "Speaking and Listening": ["S4.001", "S4.002", "S4.003", "S4.004",
                                       "S4.005", "S4.006"],
        },
        "stampFrom": "cie-igcse-english-language-2024-2026-TS3-gen",
        "stampTo": "cie-igcse-english-language-2024-2026-T2-gen",
    },
    "cie-igcse-english-language-25": {
        "vintage": "2027-2029", "fam": "F2_0500_2027",
        "blocks": {
            "Reading": ["S2.007", "S2.008", "S2.009", "S2.010", "S2.011", "S2.012"],
            "Writing": ["S2.013", "S2.014", "S2.015", "S2.016", "S2.017", "S2.018"],
            "Speaking and Listening": ["S2.019", "S2.020", "S2.021", "S2.022",
                                       "S2.023", "S2.024"],
        },
        "stampFrom": "cie-igcse-english-language-2027-2029-TS19-gen",
        "stampTo": "cie-igcse-english-language-2027-2029-T1-gen",
    },
}


def node_bytes(code, family, title, parents, order):
    # fleet node template (key order of record: code, family, title,
    # description, parents, provenanceTier, order)
    return {"code": code, "family": family, "title": title,
            "description": None, "parents": parents,
            "provenanceTier": "RULE_DERIVED", "order": order}


def edge_bytes(source, target):
    return {"source": source, "relation": "PART_OF", "target": target,
            "provenanceTier": "RULE_DERIVED"}


def rebuild_course(slug):
    spec = COURSES[slug]
    vintage, fam = spec["vintage"], spec["fam"]
    print("=" * 20, f"STREAM C: {slug} ({vintage})", "=" * 20)
    ev = json.loads((ART / "run012_official_evidence.json").read_text())[fam]
    block_order = ev["blockOrder"]
    if block_order != ["Reading", "Writing", "Speaking and Listening"]:
        fail(f"C0: evidence blockOrder drift {block_order}")
    subj_code = slug
    cdir = CONTENT / slug

    # ── C0 byte anchors + round-trip laws ──────────────────────────────
    cur_raw = (cdir / "curriculum.json").read_bytes()
    cur = json.loads(cur_raw)
    notes_raw = (cdir / "notes.json").read_bytes()
    notes = json.loads(notes_raw)
    q_raw = (cdir / "questions.json").read_bytes()
    sets = json.loads(q_raw)
    man_raw = (cdir / "manifest.json").read_bytes()
    manifest = json.loads(man_raw)
    snap_raw = (cdir / "prerequisites.json").read_bytes()
    for name, raw, obj in (("curriculum", cur_raw, cur), ("notes", notes_raw, notes),
                           ("questions", q_raw, sets), ("manifest", man_raw, manifest)):
        if dump_indent(obj) != raw:
            fail(f"C0: {name}.json round-trip law broken")
    served_raw = (KG / f"{slug}.json").read_bytes()
    served = json.loads(served_raw)
    idx_raw = (KG / "index.json").read_bytes()
    idx_rt = json.dumps(json.loads(idx_raw), ensure_ascii=False,
                        separators=(",", ":")).encode()
    if idx_rt != idx_raw:
        fail("C0: index.json serialization law drift")

    # ── C1 survivors: byte-identity or bullet+glue, position-verified ──
    pts_by_code = {n["code"]: n for n in cur["nodes"] if n["family"] == "SPEC_POINT"}
    survivors, retitles = [], []
    order_no = 0
    for blk in block_order:
        bullets = ev["bullets"][blk]
        codes = spec["blocks"][blk]
        if len(bullets) != 6 or len(codes) != 6:
            fail(f"C1: block {blk} shape drift")
        for i, (code, bullet) in enumerate(zip(codes, bullets)):
            n = pts_by_code.get(code)
            if n is None:
                fail(f"C1: survivor code {code} absent")
            if n["title"] == bullet:
                pass  # byte-exact official bullet — bytes retained
            elif n["title"].startswith(bullet):
                retitles.append({"code": code, "was": n["title"], "now": bullet})
            else:
                fail(f"C1: survivor {code} title neither byte-equal nor "
                     f"bullet-prefixed: {n['title'][:90]!r}")
            order_no += 1
            survivors.append({"code": code, "block": blk, "posInBlock": i + 1,
                              "officialTitle": bullet, "order": order_no,
                              "wasRetitled": n["title"] != bullet})
    surv_codes = [s["code"] for s in survivors]
    print(f"C1 OK: 18 survivors verified position-by-position "
          f"({len(retitles)} retitles: {[r['code'] for r in retitles]})")

    # ── C2 containers + C3 edges (mirroring the fleet template) ────────
    nodes_new, edges_new = [], []
    nodes_new.append(next(n for n in cur["nodes"] if n["family"] == "SUBJECT"))
    surv_by_code = {s["code"]: s for s in survivors}
    for ti, blk in enumerate(block_order, start=1):
        t_code = f"cie-igcse-english-language-{vintage}-T{ti}"
        sub_code = f"{t_code}:SUB{ti}.1"
        nodes_new.append(node_bytes(t_code, "TOPIC", blk, [subj_code], ti))
        nodes_new.append(node_bytes(sub_code, "SUBTOPIC", blk, [t_code], 1))
        edges_new.append(edge_bytes(subj_code, t_code))
        edges_new.append(edge_bytes(t_code, sub_code))
        for s in survivors:
            if s["block"] != blk:
                continue
            old = pts_by_code[s["code"]]
            nn = node_bytes(old["code"], "SPEC_POINT", s["officialTitle"],
                            [sub_code], s["order"])
            if not s["wasRetitled"]:
                # byte-preservation law: only parents + order change
                old_cp = {k: old[k] for k in ("code", "family", "title",
                                              "description", "provenanceTier")}
                nn_cp = {k: nn[k] for k in ("code", "family", "title",
                                            "description", "provenanceTier")}
                if old_cp != nn_cp:
                    fail(f"C2: survivor {old['code']} non-declared field drift")
            nodes_new.append(nn)
            edges_new.append(edge_bytes(sub_code, old["code"]))
    if len(nodes_new) != 25 or len(edges_new) != 24:
        fail(f"C2: rebuilt shape drift {len(nodes_new)}n/{len(edges_new)}e")
    cur_new = dict(cur)
    cur_new["nodes"] = nodes_new
    cur_new["edges"] = edges_new
    retired = len(cur["nodes"]) - len(nodes_new)
    retired_e = len(cur["edges"]) - len(edges_new)
    print(f"C2/C3 OK: rebuilt 25n/24e (retired {retired} nodes, {retired_e} edges); "
          f"parents<->edges mirrored by construction")

    (cdir / "curriculum.json").write_bytes(dump_indent(cur_new))

    # ── C4 content migration ───────────────────────────────────────────
    surv_set = set(surv_codes)
    retraction = {"notes": [], "setParts": [], "stamps": []}
    for note in notes:
        for field in ("specPointIds", "specPointCodes"):
            vals = note.get(field) or []
            dead = [c for c in vals if c not in surv_set]
            if dead:
                note[field] = [c for c in vals if c in surv_set]
                retraction["notes"].append({"noteId": note.get("noteId"),
                                            "field": field, "dropped": dead,
                                            "kept": note[field]})
    if retraction["notes"]:
        (cdir / "notes.json").write_bytes(dump_indent(notes))
    for s in sets:
        sc = s.get("subtopicCode")
        if sc == spec["stampFrom"]:
            s["subtopicCode"] = spec["stampTo"]
            retraction["stamps"].append({"set": s.get("slug"),
                                         "was": sc, "now": spec["stampTo"]})
        for q in (s.get("questions") or []):
            for p in (q.get("parts") or []):
                for field in ("specPointIds", "specPointCodes"):
                    vals = p.get(field) or []
                    dead = [c for c in vals if c not in surv_set]
                    if dead:
                        p[field] = [c for c in vals if c in surv_set]
                        retraction["setParts"].append({"set": s.get("slug"),
                                                       "partId": p.get("id"),
                                                       "field": field,
                                                       "dropped": dead,
                                                       "smeKept": bool(p.get("smeSpecPointIds"))})
    (cdir / "questions.json").write_bytes(dump_indent(sets))
    n_notes = len(retraction["notes"])
    n_parts = len(retraction["setParts"])
    print(f"C4 OK: notes retracted {n_notes} field-writes; set-part retracts "
          f"{n_parts}; stamps re-pointed {len(retraction['stamps'])} "
          f"({[x['set'] for x in retraction['stamps']]})")

    # ── C5 manifest counts sync ────────────────────────────────────────
    topics = [n for n in nodes_new if n["family"] == "TOPIC"]
    subs = [n for n in nodes_new if n["family"] == "SUBTOPIC"]
    man_counts = manifest.get("counts")
    was = dict(man_counts)
    man_counts["sections"] = len(topics)
    man_counts["topics"] = len(subs)
    man_counts["specPoints"] = len(survivors)
    (cdir / "manifest.json").write_bytes(dump_indent(manifest))
    print(f"C5 OK: manifest counts {was} -> {json.dumps(man_counts)}")

    # ── C6 KG regeneration (T-SPEC-KG-REGEN-1 in-process law) ──────────
    sys.path.insert(0, str(HUB / "scripts"))
    import kg_export  # noqa
    served_pre = {(e[0][2:], e[1][2:]) for e in served["edges"] if e[2] == "pre"}
    payload = kg_export.export_course(slug, registry())
    meta = payload["meta"]
    counts = meta["counts"]
    by_type = counts["byType"]
    if by_type != {"Section": 3, "SpecificationPoint": 18, "SubTopic": 3,
                   "Subject": 1}:
        fail(f"C6: byType drift {by_type}")
    for i, t in enumerate(topics, start=1):
        if payload["sections"][str(i)]["label"] != t["title"]:
            fail(f"C6: sec{i} label != topic title")
    if payload["sections"]["1"]["label"] != "Reading":
        fail("C6: section 1 is not Reading — array-order law broken")
    pair_labels = [lbl for defs in payload["subtopics"].values() for _, lbl in defs]
    if len(pair_labels) != 3 or set(pair_labels) != {"Reading", "Writing",
                                                     "Speaking and Listening"}:
        fail("C6: subtopic pair mirror broken")
    title_by_code = {s["code"]: s["officialTitle"] for s in survivors}
    if len(payload["points"]) != 18:
        fail(f"C6: KG points {len(payload['points'])} != 18")
    for p in payload["points"]:
        if p["text"] != kg_export.normalize_display_text(title_by_code[p["id"]]):
            fail(f"C6: KG point {p['id']} text drift")
    new_pre = {(e[0][2:], e[1][2:]) for e in payload["edges"] if e[2] == "pre"}
    if new_pre - served_pre:
        fail(f"C6: pre tier ADDED pairs {sorted(new_pre - served_pre)[:4]}")
    dying = {n["code"] for n in cur["nodes"]
             if n["family"] == "SPEC_POINT"} - surv_set
    drop_class = {"dying-prereq": 0, "dying-dependent": 0, "dying-both": 0,
                  "reversed-governance": 0}
    dropped = []
    for a, b in sorted(served_pre - new_pre):
        a_die, b_die = a not in surv_set, b not in surv_set
        if a_die and b_die:
            cls = "dying-both"
        elif a_die:
            cls = "dying-prereq"
        elif b_die:
            cls = "dying-dependent"
        elif kg_export.point_ord_key(a) > kg_export.point_ord_key(b):
            # the exporter's reversed-pair governance reads the opaque S-codes
            # (leading block letter parses to 0.0) — cross-block in-order pairs
            # classify as reversed and drop outright (unvalidated web tier,
            # conservative law). The pairs remain in the byte-untouched
            # snapshot for a future exporter lane.
            cls = "reversed-governance"
        else:
            fail(f"C6: unexplained dropped pre pair {a}->{b}")
        drop_class[cls] += 1
        dropped.append({"pair": f"{a}->{b}", "class": cls})
    hier_new = [e for e in payload["edges"] if e[2] != "pre"]
    print(f"C6 OK: KG 3sec/3sub/18pts, counts {counts['nodes']}n/"
          f"{counts['edges']}e ({len(hier_new)} hier + {len(new_pre)} pre); "
          f"pre {len(served_pre)}->{len(new_pre)} (dropped {len(dropped)}: "
          f"{json.dumps(drop_class)})")

    out_raw = json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode()
    (KG / f"{slug}.json").write_bytes(out_raw)
    idx = json.loads(idx_raw)
    row = next(r for r in idx["courses"] if r.get("slug") == slug)
    row_was = dict(row)
    row["counts"] = {"nodes": counts["nodes"], "edges": counts["edges"],
                     "specPoints": counts["specPoints"]}
    (KG / "index.json").write_bytes(
        json.dumps(idx, ensure_ascii=False, separators=(",", ":")).encode())
    print(f"C6 OK: KG written {len(out_raw)}B; index row "
          f"{row_was['counts']} -> {row['counts']}")

    return {"survivors": survivors, "retitles": retitles,
            "retiredNodes": retired, "retiredEdges": retired_e,
            "retraction": retraction,
            "manifestCounts": {"was": was, "now": man_counts},
            "kg": {"servedPre": len(served_pre), "newPre": len(new_pre),
                   "dropped": dropped, "dropClass": drop_class,
                   "counts": counts},
            "indexRow": {"was": row_was, "now": row}}


if __name__ == "__main__":
    out = {}
    for slug in COURSES:
        out[slug] = rebuild_course(slug)
    (ART / "run012_0500_rebuild_census.json").write_text(json.dumps(out, indent=1))
    print("EXEC C: DONE — census -> run012_0500_rebuild_census.json")
