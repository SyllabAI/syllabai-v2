#!/usr/bin/env python3
"""T-TEACHGENIE-003 — regenerate apps/api/src/teach-me/prompts.ts.

The pinned-prompt law (T-MIG-039): the TS module must be byte-identical to the
pinned .md sources. This generator embeds each .md verbatim (JSON escaping is
lossless) so the deploy artifact carries no loose files. Re-run after any
version bump; never hand-edit the output.

T-TEACHGENIE-003 ("Teach SillyAI" rebrand): pupil.v3 + teachme.turn.v3 carry the
renamed SillyAI persona (was v2 "Baby Genie"); review stays v1 (persona-free).
The v2 sources stay checked in beside them as the pinned history.
"""
import json
from pathlib import Path

PROMPTS_DIR = Path(__file__).resolve().parents[1] / "apps/api/src/teach-me/prompts"
OUT = PROMPTS_DIR.parent / "prompts.ts"

OBJECTIVES_SYSTEM_V3 = (
    "# Pinned prompt `teachme.objectives.v3` — canon-grounded objective generator + session opener (LLM call 1)\n"
    "\n"
    "You are generating the teaching objectives AND the opening message for a\n"
    "learn-by-teaching session. The student picked the spec points below from the\n"
    "course's canonical spec tree. You NEVER invent facts, terms or spec-point ids:\n"
    "every objective is a rephrasing of the given titles/descriptions in\n"
    "pupil-facing language (\"Explain ...\", \"Describe ...\", \"Walk me through ...\").\n"
    "Do not number the objectives. Do not add objectives for spec points you were\n"
    "not given. Each objective cites the spec point id(s) it draws from.\n"
    "\n"
    "The `openingMessage` is SillyAI's first message of the session, in character\n"
    "per the pupil charter voice (casual, lowercase sentence starts, contractions):\n"
    "a confused younger student asking the user to teach them about the picked\n"
    "topics. It MUST reference the actual topic wording from the spec points given\n"
    "(like \"i'm a bit muddled about elements, compounds, and mixtures — could you\n"
    "help me tell them apart?\"), be 1-3 sentences, end with a request or question,\n"
    "and NEVER mention objectives, sessions, judging or that you are an AI.\n"
    "\n"
    "Output — ONE JSON object, no prose, no markdown fence:\n"
    '{"objectives": [{"text": "...", "specPointIds": ["..."]}], "openingMessage": "..."}\n'
)


def embed(name: str, value: str) -> str:
    return f"export const {name}: string =\n  {json.dumps(value)};\n"


pupil = (PROMPTS_DIR / "pupil-v3.md").read_text(encoding="utf-8")
turn = (PROMPTS_DIR / "teachme-turn-v3.md").read_text(encoding="utf-8")
review = (PROMPTS_DIR / "teachme-review-v1.md").read_text(encoding="utf-8")
review2 = (PROMPTS_DIR / "teachme-review-v2.md").read_text(encoding="utf-8")

body = "\n".join(
    [
        "/**",
        " * T-TEACHME-001 · run-002 · apps/api/src/teach-me/prompts.ts",
        " * T-TEACHGENIE-003 · regenerated for Teach SillyAI (pupil.v3, turn.v3,",
        " * objectives.v3 with the SillyAI opener; review stays v1).",
        " *",
        " * PINNED PROMPTS — generated byte-exact from the pinned .md sources by",
        " * scripts/gen_prompts_ts.py (re-run it; do not hand-edit). The behavioural",
        " * suite asserts byte-equality of these strings against the .md files checked",
        " * in beside them (T-MIG-039).",
        " */",
        "",
        embed("PUPIL_CHARTER_V3", pupil),
        embed("TEACHME_TURN_V3", turn),
        embed("TEACHME_REVIEW_V1", review),
embed("TEACHME_REVIEW_V2", review2),
        embed("OBJECTIVES_SYSTEM_V3", OBJECTIVES_SYSTEM_V3),
    ]
)

OUT.write_text(body, encoding="utf-8")
print(f"wrote {OUT} ({len(body)} bytes)")
