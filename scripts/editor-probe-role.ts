/**
 * ADR-044 run-006 · scripts/editor-probe-role.ts
 *
 * The CREATE-ROLE viability probe — the operator fork's decision evidence
 * (receipt .syllabai/receipts/ADR-044/run-006-grants-apply-inheritance-fork-r0.md,
 * fork option 2: the app-role re-provisioning cutover). COW-ONLY by design:
 * the runner invokes it on the disposable branch with the branch-local owner
 * URI; this script is never wired to a production URI (zero prod contact).
 *
 * It asks exactly three questions, measured not guessed:
 *   P1 — can the connected vantage CREATE ROLE at all (neondb_owner
 *        CREATEROLE on this Neon build)? The measured ALTER refusal
 *        (run-005) proved the owner cannot ALTER the platform-provisioned
 *        app role; creating a SUCCESSOR role is the fork-2 path and needs
 *        CREATE, which is a different privilege.
 *   P2 — is a SQL-created role FREE of platform memberships? The app role's
 *        defect is the platform-provisioned INHERIT membership in
 *        neon_superuser (console/API-created roles get it). A fresh
 *        SQL-created role must hold ZERO memberships for the fork-2 wire
 *        proofs to be enforceable.
 *   P3 — does a fresh role hold EXACTLY its granted verb set? The critical
 *        negative: has_table_privilege(UPDATE) on a SELECT-only table must
 *        read FALSE — on the platform-provisioned app role it reads TRUE
 *        via the membership chain (run-004's named residual path).
 *
 * Green on all three ⇒ fork option 2 is viable end-to-end. Any miss ⇒ the
 * receipt names it and the fork collapses to option 1 (Neon platform
 * request) or option 3 (ADR amendment).
 *
 * House laws honored: a receipt JSON is ALWAYS written (even on failure);
 * credentials never enter the receipt (host only); best-effort zero residue
 * (probe table + role dropped in the finally block — the branch dies at leg
 * end regardless); fail-closed honesty (a red receipt is the answer).
 *
 * CLI:
 *   bun scripts/editor-probe-role.ts --db file:/tmp/uri.file \
 *     --receipt receipt.json
 */

import { randomUUID } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import postgres from "postgres";

function arg(name: string): string {
	const i = process.argv.indexOf(`--${name}`);
	if (i === -1 || i + 1 >= process.argv.length) {
		console.error(`missing --${name}`);
		process.exit(2);
	}
	return process.argv[i + 1]!;
}

const dbArg = arg("db");
const receiptPath = arg("receipt");

let uri = dbArg.startsWith("file:") ? readFileSync(dbArg.slice(5), "utf8").trim() : dbArg;
uri = uri.trim();
if (!uri.includes("sslmode=")) uri += (uri.includes("?") ? "&" : "?") + "sslmode=require";
const uriHost = new URL(uri).host;

const receipt: Record<string, unknown> = {
	card: "EDITOR-ROLE-CREATE-PROBE (ADR-044 run-006 fork evidence — COW-only)",
	driver: "scripts/editor-probe-role.ts",
	db_host: uriHost,
	started_at: new Date().toISOString(),
};
const writeReceipt = (ok: boolean) => {
	receipt.finished_at = new Date().toISOString();
	receipt.ok = ok;
	writeFileSync(receiptPath, JSON.stringify(receipt, null, 2) + "\n");
};

const sql = postgres(uri, { max: 1, prepare: false, connect_timeout: 15 });

// Hex-only identifiers generated by this process — safe to quote-interpolate.
const SUFFIX = randomUUID().replace(/-/g, "").slice(0, 12);
const ROLE = `editor_probe_${SUFFIX}`;
const TABLE = `editor_probe_t_${SUFFIX}`;

try {
	// ── P1: CREATE ROLE (the fork-2 gate) ────────────────────────────────────
	await sql.unsafe(`CREATE ROLE "${ROLE}" NOLOGIN`);
	receipt.p1_create_role = {
		ok: true,
		role: ROLE,
		note: "the connected vantage CAN create roles — the successor-role cutover path is not dead on arrival",
	};

	// ── P2: the fresh role's membership census (expect ZERO) ────────────────
	const memberships = (
		await sql`SELECT g.rolname AS granted_role FROM pg_auth_members m JOIN pg_roles g ON g.oid = m.roleid JOIN pg_roles r ON r.oid = m.member WHERE r.rolname = ${ROLE}`
	).map((r) => r.granted_role as string);
	receipt.p2_memberships = {
		memberships,
		clean: memberships.length === 0,
		note:
			memberships.length === 0
				? "a SQL-created role holds NO platform memberships — the neon_superuser INHERIT defect does NOT reproduce for SQL-created roles"
				: "the platform attached memberships to a SQL-created role — fork option 2 would inherit the SAME defect; collapsed to fork option 1/3",
	};

	// ── P3: the verb-set battery on a scratch table ─────────────────────────
	await sql.unsafe(`CREATE TABLE "${TABLE}" (i int)`);
	await sql.unsafe(`GRANT SELECT ON TABLE public."${TABLE}" TO "${ROLE}"`);
	const pos = (await sql`SELECT has_table_privilege(${ROLE}, ${`public.${TABLE}`}, 'SELECT') AS ok`)[0]?.ok as boolean;
	const negU = (await sql`SELECT has_table_privilege(${ROLE}, ${`public.${TABLE}`}, 'UPDATE') AS ok`)[0]?.ok as boolean;
	const negD = (await sql`SELECT has_table_privilege(${ROLE}, ${`public.${TABLE}`}, 'DELETE') AS ok`)[0]?.ok as boolean;
	const negT = (await sql`SELECT has_table_privilege(${ROLE}, ${`public.${TABLE}`}, 'TRUNCATE') AS ok`)[0]?.ok as boolean;
	receipt.p3_verb_set = {
		select_granted: pos === true,
		update_denied: negU === false,
		delete_denied: negD === false,
		truncate_denied: negT === false,
		note: "the critical negative is UPDATE denied on a SELECT-only table — on the platform-provisioned app role this reads TRUE via the membership chain (run-004)",
	};

	const ok = pos === true && negU === false && negD === false && negT === false && memberships.length === 0;
	receipt.verdict = ok
		? "FORK-OPTION-2 VIABLE: a SQL-created role is membership-free and holds exactly its granted verb set — the re-provisioning cutover is the measured path"
		: "FORK-OPTION-2 BLOCKED: see p1/p2/p3 for the measured miss — collapse to fork option 1 (Neon platform request) or option 3 (ADR amendment)";
	receipt.ok = ok;
	writeReceipt(true);
	console.log(ok ? "probe GREEN — fork option 2 viable" : "probe RED — fork option 2 blocked");
} catch (err) {
	receipt.error = err instanceof Error ? err.message : String(err);
	console.error("EDITOR-ROLE-CREATE-PROBE failed:", receipt.error);
	receipt.verdict = "FORK-OPTION-2 BLOCKED (probe error above) — collapse to fork option 1 (Neon platform request) or option 3 (ADR amendment)";
	writeReceipt(false);
	process.exitCode = 1;
} finally {
	try {
		await sql.unsafe(`DROP TABLE IF EXISTS public."${TABLE}"`);
		await sql.unsafe(`DROP ROLE IF EXISTS "${ROLE}"`);
	} catch {
		// the branch dies at leg end regardless; never mask the primary verdict
	}
	await sql.end({ timeout: 5 });
}
