TRAIL = re.compile(r"\s*[bcpp]\d+\.\d+(?:\.\d+)?[a-z]?\s+[a-z][^.]{2,}\s*$")
TRAIL2 = re.compile(r"\s*\d+\.\d+(?:\.\d+)?[a-z]?\s+[a-z][^.]{2,}\s*$")


def strip_tail(s):
    s = s.lower().strip()
    for _ in range(3):
        new = TRAIL2.sub("", TRAIL.sub("", s))
        if new == s:
            break
        s = new
    return s


def norm(s):
    return re.sub(r"\s+", " ", strip_tail(s).strip())


def toks(s):
    return Counter(re.findall(r"[a-z0-9]+", s))


def seq(a, b):
    return SequenceMatcher(None, a, b).ratio()


def contain(a, b):
    ta, tb = toks(a), toks(b)
    return sum((ta & tb).values()) / min(sum(ta.values()), sum(tb.values()))


def jacc(a, b):
    ta, tb = toks(a), toks(b)
    return sum((ta & tb).values()) / sum((ta | tb).values())


def load(slug):
    return json.loads((DATA / f"{slug}.json").read_text())


def fail(msg):
    print(f"FAIL: {msg}", flush=True)
    sys.exit(2)


