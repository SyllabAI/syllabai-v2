def build_map(subject, coord_pts, sep_pts):
    sep_by_norm = {}
    for p in sep_pts:
        sep_by_norm.setdefault(norm(p["text"]), p["id"])
    auto, fuzzy = {}, {}
    for p in coord_pts:
        pid = p["id"]
        if pid in MANUAL[subject] or pid in SPLITS[subject] or pid in UNANCHORED[subject]:
            continue
        t = norm(p["text"])
        if t in sep_by_norm and len(t) > 3:
            auto[pid] = sep_by_norm[t]
            continue
        best = None
        for k, dp in sep_by_norm.items():
            s, j = max(seq(t, k), contain(t, k)), jacc(t, k)
            if best is None or (s, j) > (best[0], best[1]):
                best = (s, j, dp)
        if len(t) > 3 and best[0] >= 0.999 and seq(t, norm(next(k for k, dp in sep_by_norm.items() if dp == best[2]))) >= 0.999:
            auto[pid] = best[2]
            continue
        if len(t) > 3 and best[0] >= 0.85 and best[1] >= 0.45:
            auto[pid] = best[2]
            fuzzy[(pid, best[2])] = (best[0], best[1])
            continue
        fail(f"{subject}: D1 residue point {pid} unresolved (best {best[2]} score {best[0]:.3f} jacc {best[1]:.3f})")
    # D2 — injectivity of the combined map (auto + manual), with split targets
    combined = dict(auto)
    for src, (dst, ev) in MANUAL[subject].items():
        combined[src] = dst
    splits = {s: d for s, (d, ev) in SPLITS[subject].items()}
    claims = Counter(combined.values())
    for src, dst in splits.items():
        claims[dst] += 1
    multi = {d: c for d, c in claims.items() if c > 1}
    allowed_multi = set(splits.values())
    bad = set(multi) - allowed_multi
    if bad:
        claimants = {}
        for src, dst in list(combined.items()) + [(s, d) for s, d in splits.items()]:
            if dst in bad:
                claimants.setdefault(dst, []).append(src)
        fail(f"{subject}: D2 non-injective targets not disclosed as splits: {sorted(bad)} — claimants {claimants}")
    for s in splits:
        if s in combined:
            fail(f"{subject}: D2 split point {s} also auto/manual-mapped")
    return combined, splits, fuzzy, auto


def derive(subject):
    coord = load(COORD_SLUG[subject])
    sep = load(SEP_SLUG[subject])
    m_concepts, m_edges = master(subject)
    sep_ids = {p["id"] for p in sep["points"]}
    coord_ids = [p["id"] for p in coord["points"]]

    # master anchor integrity
    for cid, b in m_concepts.items():
        out = [x for x in b if x not in sep_ids]
        if out:
            fail(f"{subject}: master concept {cid} anchors outside sep spine: {out}")
    bind_union = [x for b in m_concepts.values() for x in b]
    dup_master = {x for x, c in Counter(bind_union).items() if c > 1}
    # inherited master double-anchors (e.g. the 0620 snapshot's ORGANIC-NAMING /
    # ALCOHOL both bind 11.2.3) are the master's authored shape, already served
    # and QA-accepted on the donor course; export_pairs drops the resulting
    # self-loop pairs. D4 requires: any double-anchoring AFTER remap must be
    # inherited from the master, never introduced by the remap.
    if subject == "chem":
        print(f"{subject}: NOTE inherited master double-anchored donor points: {sorted(dup_master)}")

    combined, splits, fuzzy, auto = build_map(subject, coord["points"], sep["points"])

    # inverse donor -> co-ord
    inv = {}
    for cp, dp in combined.items():
        inv.setdefault(dp, []).append(cp)
    for sp_, dp in splits.items():
        inv.setdefault(dp, []).append(sp_)

    concepts = {}
    for cid, binds in m_concepts.items():
        nb = []
        for d in binds:
            nb.extend(inv.get(d, []))
        if nb:
            concepts[cid] = sorted(set(nb))
    edges = [e for e in m_edges if e[0] in concepts and e[1] in concepts]

    # D4b — remap must not INTRODUCE new double-anchoring beyond the master's
    bind_union_new = [x for b in concepts.values() for x in b]
    dup_new = {x for x, c in Counter(bind_union_new).items() if c > 1}
    # a co-ord point is double-anchored after remap only if two master concepts
    # shared one of its donor pre-images — i.e. inherited
    inherited_ok = set()
    for cp, dpoint in combined.items():
        if dpoint in dup_master:
            inherited_ok.add(cp)
    for sp_, dpoint in splits.items():
        if dpoint in dup_master:
            inherited_ok.add(sp_)
    novel = dup_new - inherited_ok
    if novel:
        fail(f"{subject}: D4b remap introduced new double-anchored points: {sorted(novel)}")
    if dup_new:
        print(f"{subject}: NOTE double-anchored co-ord points (inherited): {sorted(dup_new)}")

    # D3 hygiene
    seen = set()
    for a, b, bas in edges:
        if bas not in BASIS:
            fail(f"{subject}: basis {bas!r} outside vocab on edge {a}->{b}")
        if a == b or (a, b) in seen or (b, a) in seen:
            fail(f"{subject}: self/dup/mutual edge {(a, b)}")
        if a not in concepts or b not in concepts:
            fail(f"{subject}: edge endpoint not in concepts {(a, b)}")
        seen.add((a, b))

    # D4 — survivors anchored; coverage of the target spine
    covered = set()
    for cid, b in concepts.items():
        covered.update(b)
    uncovered_mapped = [cp for cp in coord_ids if cp in combined and cp not in covered]
    for cid, b in concepts.items():
        if not b:
            fail(f"{subject}: D4 concept {cid} survived with zero anchors")
    uncovered_mapped = [cp for cp in coord_ids if cp in combined and cp not in covered]

    # D5 — export against the TARGET spine order (law of record)
    order = {p["id"]: i for i, p in enumerate(coord["points"])}
    web = [{"prerequisite": a, "dependent": b, "basis": bas} for a, b, bas in edges]
    pairs, stats = P.export_pairs(web, concepts, order)
    rev_exact = []
    for a, b, _ in edges:
        for x in concepts[a]:
            for y in concepts[b]:
                if x != y and order[x] > order[y]:
                    rev_exact.append((a, b, x, y))
    rev_exact.sort()

    return {
        "coord": coord, "sep": sep, "concepts": concepts, "edges": edges,
        "combined": combined, "splits": splits, "fuzzy": fuzzy, "auto": auto,
        "uncovered_mapped": uncovered_mapped, "unanchored": sorted(UNANCHORED[subject]),
        "stats": stats, "rev": rev_exact, "pairs": pairs,
    }


def fmt_rev(rev):
    if not rev:
        return "  (none — every kept dependency is served in-order)"
    return "\n".join(f"  - {a} [{x}] -> {b} [{y}]" for a, b, x, y in rev)


def emit(path, docstring, concepts, edges):
    body = [docstring, '\nDD = "DEFINITIONAL_DEPENDENCY"', 'UWR = "USED_WITHOUT_RETEACHING"', "", "CONCEPTS = {"]
    for cid, binds in concepts.items():
        body.append(f'    "{cid}": {json.dumps(binds)},')
    body.append("}")
    body.append("")
    body.append("EDGES = [")
    for a, b, bas in edges:
        short = "DD" if bas == DD else "UWR"
        body.append(f'    ("{a}", "{b}", {short}),')
    body.append("]")
    path.write_text("\n".join(body) + "\n")
    print(f"EMITTED {path.name}: concepts {len(concepts)}, edges {len(edges)}")


