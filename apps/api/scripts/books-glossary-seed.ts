/**
 * T-BOOK-007 — the glossary seeding script: L1 corpus (chunks_v3, the parse
 * of record) → the glossary YAML skeleton (L2 authoring workspace).
 *
 * OFFLINE by law: reads the jsonl path from argv, writes a skeleton file —
 * NO database, NO network (L1 is append-only reference material; the write
 * target is the L2 pack workspace, PR-gated like every authored artifact).
 *
 * The 21 glossary chunks of the 4CH1 parse (census of record: glossary 21)
 * carry the book's own glossary text. This script EXTRACTS term/definition
 * candidates heuristically (term-dash-definition lines, then first-sentence
 * fallbacks) and marks every entry `needs_ms_language: true` — the authored
 * pass (T-BOOK-010 S2) writes the real value-add: ≤40-word examiner-safe
 * definitions + ms_accepts/ms_avoids. The seed is a floor, never shipped.
 *
 * Usage: bun apps/api/scripts/books-glossary-seed.ts <chunks.jsonl> <out.yaml> [subjectCode]
 */
import { readFileSync, writeFileSync } from "node:fs";

function kebab(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

interface Chunk {
  id: string;
  content_type: string;
  chapter_no: number | null;
  book_pages: [number, number] | null;
  text: string;
}

const [inputPath, outPath, subjectCode = "4ch1"] = process.argv.slice(2);
if (inputPath == null || outPath == null) {
  console.error("usage: books-glossary-seed.ts <chunks.jsonl> <out.yaml> [subjectCode]");
  process.exit(1);
}

const lines = readFileSync(inputPath, "utf8").split("\n").filter((l) => l.trim() !== "");
const chunks: Chunk[] = [];
for (const line of lines) {
  try {
    const row = JSON.parse(line) as Chunk;
    if (row.content_type === "glossary") chunks.push(row);
  } catch {
    // a malformed corpus line is skipped — the census counts only parseable rows
  }
}

if (chunks.length === 0) {
  console.error("seed: ZERO glossary chunks found — wrong file? (census of record: 21)");
  process.exit(2);
}

/**
 * Term/definition candidates from one chunk's text. THE ACTUAL FORMAT OF
 * RECORD (verified against the 21 chunks): newline-separated entries of
 * "term definition" with NO separator — the term/definition boundary is
 * frequently OCR-glued ("amphotericsubstances"). A regex CANNOT split that
 * reliably, so the seed is HONEST about it: one candidate per entry line,
 * term_guess = the leading word run (the entries are alphabetised — the
 * first word is nearly always inside the term), raw_entry preserved, and
 * needs_ms_language: true on EVERY entry. The authored pass does the split.
 */
function entries(text: string): Array<{ termGuess: string; rawEntry: string }> {
  const out: Array<{ termGuess: string; rawEntry: string }> = [];
  for (const rawLine of text.split("\n")) {
    const line = rawLine.trim();
    if (line === "" || /^GLOSSARY$/i.test(line)) continue;
    const words = line.split(/\s+/);
    if (words.length < 2) continue;
    // leading word run: stop at the first word of ≥8 chars followed by a
    // lowercase continuation (the definition's first word is usually a
    // short function word or a clear sentence start)
    let stop = 1;
    for (let i = 1; i < Math.min(words.length, 4); i++) {
      const w = words[i]!;
      const next = words[i + 1];
      const wIsTermish = w.length <= 12 && /^[a-z0-9()³²-]+$/i.test(w);
      const nextIsDefish = next != null && next.length >= 6 && /^[a-z]/.test(next);
      if (wIsTermish && nextIsDefish && i >= 1) stop = i + 1;
      else break;
    }
    const termGuess = words.slice(0, stop).join(" ").replace(/[^A-Za-z0-9()\s³-]/g, "").trim();
    if (termGuess === "" || termGuess.length > 40) continue;
    out.push({ termGuess, rawEntry: line });
  }
  return out;
}

interface SeedEntry {
  term: string;
  slug: string;
  /** the raw entry text of record — the authored pass splits term/definition from it */
  definition: string;
  source: string;
  needs_ms_language: boolean;
}

const seen = new Set<string>();
const seeds: SeedEntry[] = [];
for (const chunk of chunks) {
  for (const e of entries(chunk.text)) {
    const slug = kebab(e.termGuess);
    if (slug === "" || seen.has(slug)) continue;
    seen.add(slug);
    seeds.push({
      term: e.termGuess,
      slug,
      definition: e.rawEntry,
      source: `seed:chunks_v3#${chunk.id}${chunk.book_pages ? `:p${chunk.book_pages[0]}` : ""}`,
      needs_ms_language: true,
    });
  }
}

const yaml = [
  `# T-BOOK-007 seed of record — generated by apps/api/scripts/books-glossary-seed.ts`,
  `# from the L1 parse of record (${inputPath.split("/").pop()}): ${chunks.length} glossary chunks,`,
  `# ${seeds.length} unique term candidates. EVERY entry carries needs_ms_language:`,
  `# the authored pass (BOOK-PACK-SPEC §5) writes the ≤40-word examiner-safe`,
  `# definition + ms_accepts/ms_avoids. The seed is a floor, never shipped.`,
  `subject_code: "${subjectCode}"`,
  "terms:",
  ...seeds.flatMap((s) => [
    `  - term: ${JSON.stringify(s.term)}`,
    `    slug: ${s.slug}`,
    `    definition: ""            # AUTHORED PASS — write the ≤40-word examiner-safe definition`,
    `    raw_entry: ${JSON.stringify(s.definition)}`,
    `    source: "${s.source}"`,
    `    needs_ms_language: true`,
  ]),
].join("\n");

writeFileSync(outPath, yaml + "\n");
console.log(`seed: ${chunks.length} glossary chunks → ${seeds.length} unique candidates → ${outPath}`);
